"""Traffic management reports (FR-18).

A report is a snapshot: analytics plus the current state of signals, alerts,
parking and emergency requests. It is stored (FR-19) so it can be opened or
downloaded again later exactly as it was generated.
"""
import json

import alerts
import analytics
import emergency
import parking
import signals

DEFAULT_TITLE = "Traffic management report"
MAX_TITLE = 100


def init_reports(conn):
    conn.execute(
        """CREATE TABLE IF NOT EXISTS reports (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            title TEXT NOT NULL,
            generated_by TEXT NOT NULL,
            content TEXT NOT NULL,
            created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
        )"""
    )
    conn.commit()


def _count_by(items, key):
    counts = {}
    for item in items:
        counts[item[key]] = counts.get(item[key], 0) + 1
    return counts


def build_content(conn, title, actor):
    current_alerts = alerts.list_alerts(conn)
    requests = emergency.list_requests(conn)
    open_incidents = conn.execute(
        "SELECT id, type, location, status FROM incidents "
        "WHERE status != 'Closed' ORDER BY id DESC LIMIT 10").fetchall()
    return {
        "title": title,
        "generated_by": actor,
        "generated_at": conn.execute(
            "SELECT CURRENT_TIMESTAMP").fetchone()[0],
        "analytics": analytics.analyze(conn),
        "signals": {
            "total": len(signals.list_signals(conn)),
            "by_state": _count_by(signals.list_signals(conn), "state"),
        },
        "alerts": {
            "active": len(current_alerts),
            "by_kind": _count_by(current_alerts, "kind"),
        },
        "parking": parking.summary(conn),
        "emergency": {
            "requests": len(requests),
            "active": sum(1 for r in requests if r["status"] == "Active"),
        },
        "open_incidents": [dict(r) for r in open_incidents],
    }


def generate(conn, actor, title=None):
    """Create and store a report. Does not commit. Returns it."""
    title = (title or DEFAULT_TITLE).strip() or DEFAULT_TITLE
    if len(title) > MAX_TITLE:
        raise ValueError("Title must be at most %d characters" % MAX_TITLE)
    content = build_content(conn, title, actor)
    cur = conn.execute(
        "INSERT INTO reports (title, generated_by, content) VALUES (?, ?, ?)",
        (title, actor, json.dumps(content)))
    return get_report(conn, cur.lastrowid)


def list_reports(conn):
    rows = conn.execute(
        "SELECT id, title, generated_by, created_at FROM reports "
        "ORDER BY id DESC LIMIT 100").fetchall()
    return [dict(r) for r in rows]


def get_report(conn, report_id):
    row = conn.execute(
        "SELECT id, title, generated_by, created_at, content FROM reports "
        "WHERE id = ?", (report_id,)).fetchone()
    if row is None:
        return None
    report = dict(row)
    report["content"] = json.loads(report["content"])
    return report


def _kv(mapping):
    return ", ".join("%s: %s" % (k, v) for k, v in mapping.items()) or "none"


def render_text(report):
    """A plain-text version that can be printed or emailed."""
    c = report["content"]
    a = c["analytics"]
    flow, cong, inc, pat = (a["traffic_flow"], a["congestion"],
                            a["incidents"], a["patterns"])
    lines = [
        c["title"].upper(),
        "Report #%d | generated by %s | %s UTC" % (
            report["id"], c["generated_by"], c["generated_at"]),
        "",
        "1. TRAFFIC FLOW",
        "  Average density: %s%%" % flow["average_density"],
        "  Roads by congestion: %s" % _kv(flow["levels"]),
    ]
    if flow["busiest"]:
        lines.append("  Busiest road: %s (%s%%)" % (
            flow["busiest"]["name"], flow["busiest"]["density"]))
        lines.append("  Quietest road: %s (%s%%)" % (
            flow["quietest"]["name"], flow["quietest"]["density"]))
    lines += ["", "2. CONGESTION",
              "  Readings analysed: %d" % cong["readings_analysed"]]
    for road in cong["most_congested"]:
        lines.append("  %s: heavy in %d%% of %d readings" % (
            road["name"], road["high_percent"], road["readings"]))
    lines += ["", "3. INCIDENTS",
              "  Total: %d (open: %d)" % (inc["total"], inc["open"]),
              "  By type: %s" % _kv(inc["by_type"]),
              "  By status: %s" % _kv(inc["by_status"])]
    for spot in inc["hotspots"]:
        lines.append("  Hotspot: %s (%d)" % (spot["location"],
                                             spot["incidents"]))
    lines += ["", "4. TRAFFIC PATTERNS"]
    if pat["peak_hour"] is None:
        lines.append("  Not enough history yet.")
    else:
        lines.append("  Peak hour (UTC): %s:00, quietest: %s:00" % (
            pat["peak_hour"], pat["quietest_hour"]))
    for trend in pat["road_trends"]:
        lines.append("  %s: %s (%s%% -> %s%%)" % (
            trend["road"], trend["trend"], trend["earlier_average"],
            trend["recent_average"]))
    p, s = c["parking"], c["signals"]
    lines += [
        "", "5. SYSTEM STATE",
        "  Signals: %d (%s)" % (s["total"], _kv(s["by_state"])),
        "  Active alerts: %d (%s)" % (c["alerts"]["active"],
                                      _kv(c["alerts"]["by_kind"])),
        "  Parking: %d of %d spaces free in %d areas" % (
            p["total_available"], p["total_capacity"], p["areas"]),
        "  Emergency requests: %d (active: %d)" % (
            c["emergency"]["requests"], c["emergency"]["active"]),
    ]
    if c["open_incidents"]:
        lines += ["", "OPEN INCIDENTS"]
        for item in c["open_incidents"]:
            lines.append("  #%d %s at %s [%s]" % (
                item["id"], item["type"], item["location"], item["status"]))
    return "\n".join(lines) + "\n"
